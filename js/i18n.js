// Language config
const LANG_CONFIG = {
  fr: { name: 'Français', flag: '🇫🇷', dir: 'ltr', font: '' },
  en: { name: 'English',  flag: '🇬🇧', dir: 'ltr', font: '' },
  es: { name: 'Español',  flag: '🇪🇸', dir: 'ltr', font: '' },
  ar: { name: 'العربية', flag: '🇸🇦', dir: 'rtl', font: "'Cairo', 'Amiri', sans-serif" }
};

class I18n {
  constructor() {
    this.current = localStorage.getItem('rw_lang') || 'fr';
    this.apply();
  }

  t(key) {
    return TRANSLATIONS[this.current]?.[key] || TRANSLATIONS['fr'][key] || key;
  }

  set(lang) {
    if (!LANG_CONFIG[lang]) return;
    this.current = lang;
    localStorage.setItem('rw_lang', lang);
    this.apply();
    this.render();
  }

  apply() {
    const cfg = LANG_CONFIG[this.current];
    document.documentElement.lang = this.current;
    document.documentElement.dir  = cfg.dir;
    if (cfg.font) document.body.style.fontFamily = cfg.font;
    else document.body.style.fontFamily = '';
    // Load Arabic fonts if needed
    if (this.current === 'ar') {
      const link = document.getElementById('arabic-font');
      if (!link) {
        const el = document.createElement('link');
        el.id = 'arabic-font';
        el.rel = 'stylesheet';
        el.href = 'https://fonts.googleapis.com/css2?family=Cairo:wght@400;600;700&display=swap';
        document.head.appendChild(el);
      }
    }
  }

  render() {
    // Update all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      el.textContent = this.t(key);
    });
    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.dataset.i18nPlaceholder);
    });
    // Update lang selector display
    document.querySelectorAll('.lang-current').forEach(el => {
      el.textContent = `${LANG_CONFIG[this.current].flag} ${LANG_CONFIG[this.current].name}`;
    });
    document.querySelectorAll('.lang-option').forEach(el => {
      el.classList.toggle('active', el.dataset.lang === this.current);
    });
  }
}

// Global instance
const i18n = new I18n();
window.i18n = i18n;

// Auto-render on DOM ready
document.addEventListener('DOMContentLoaded', () => i18n.render());
